/* Showcase shell: stacking view + clickable plans + panoramas + 3D link, all from manifest.json.
   Every value shown comes from the manifest (built from the IFC and the spec library); text is set with
   textContent, never innerHTML, except the plan SVGs the build script wrote. */
(function () {
  "use strict";
  var $ = function (s) { return document.querySelector(s); };
  var el = function (tag, cls, text) { var e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; };
  var M, X = null, byId = {}, svgCache = {}, cur = { storey: null, sel: null }, pano = null, panoCur = null;

  function title(s) { return String(s || "").toLowerCase().replace(/(^|[\s(])\S/g, function (c) { return c.toUpperCase(); }); }
  function storeyOf(id) { return M.storeys.find(function (s) { return s.id === id || s.name === id; }); }
  function m2(a) { return a == null ? "Not in model" : a.toFixed(1) + " m²"; }

  // ------------------------------------------------------------ explore (layer 3) links
  function exploreHref(item) {
    var st = storeyOf(item.storey), lvl = st ? st.id : "";
    if (X && X.rooms) {
      var word = new RegExp("(^|[^0-9a-z])" + String(item.name).replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "([^0-9a-z]|$)", "i");
      var hit = X.rooms.find(function (r) {
        return r.id === item.id || r.plan_room === item.id || (r.space && (word.test(r.space) || (item.ifc || []).indexOf(r.ifc) >= 0));
      });
      if (hit) return "explore/index.html?view=room:" + encodeURIComponent(hit.id) + "&level=" + encodeURIComponent(hit.storey || lvl);
    }
    return "explore/index.html?view=cutaway&level=" + encodeURIComponent(lvl);
  }

  // ------------------------------------------------------------ stacking view
  function buildStack() {
    var box = $("#stack");
    M.storeys.slice().reverse().forEach(function (st) {
      var b = el("div", "level"); b.setAttribute("role", "button"); b.tabIndex = 0; b.dataset.storey = st.id;
      b.appendChild(el("span", "lname", title(st.name)));
      var cells = el("div", "cells");
      var units = st.units.map(function (u) { return byId[u]; });
      if (!units.length) cells.appendChild(el("span", "cell none", st.rooms.length ? "Common" : ""));
      units.forEach(function (u) {
        var c = el("span", "cell", u.name); c.style.setProperty("--w", Math.max(1, Math.round((u.area || 50) / 40)));
        c.title = u.name + (u.area ? ", " + m2(u.area) : ""); c.dataset.unit = u.id;
        c.addEventListener("click", function (e) { e.stopPropagation(); selectStorey(st.id, u.id); });
        cells.appendChild(c);
      });
      b.appendChild(cells);
      var go = function () { selectStorey(st.id); };
      b.addEventListener("click", go);
      b.addEventListener("keydown", function (e) { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); go(); } });
      box.appendChild(b);
    });
  }

  // ------------------------------------------------------------ plan
  function selectStorey(id, select) {
    var st = storeyOf(id); if (!st) return;
    cur.storey = st.id;
    document.querySelectorAll(".level").forEach(function (b) { b.setAttribute("aria-pressed", b.dataset.storey === st.id); });
    $("#level-name").textContent = title(st.name);
    var nU = st.units.length, nR = st.rooms.length;
    $("#level-note").textContent = (nU ? nU + (nU > 1 ? " residences, " : " residence, ") : "") + nR + " areas · floor at RL " + st.elevation.toFixed(2);
    var load = svgCache[st.svg] ? Promise.resolve(svgCache[st.svg]) : fetch(st.svg).then(function (r) { if (!r.ok) throw r.status; return r.text(); });
    load.then(function (txt) {
      svgCache[st.svg] = txt;
      if (cur.storey !== st.id) return;
      var plan = $("#plan"); plan.innerHTML = txt;  // generated by build.py from the IFC, names escaped there
      var svg = plan.querySelector("svg"); svg.setAttribute("role", "img"); svg.setAttribute("aria-label", "Floor plan, " + title(st.name));
      addCameras(svg, st);
      svg.addEventListener("click", function (e) {
        var t = e.target.closest("[data-room],[data-unit],[data-pano]");
        if (!t) return;
        if (t.dataset.pano) { openPano(t.dataset.pano, true); return; }
        selectItem(t.dataset.room || t.dataset.unit);
      });
      if (select) selectItem(select);
      else hideDetail();
    }).catch(function () { $("#plan").innerHTML = ""; $("#plan").appendChild(el("p", "plan-empty", "Plan not built for this level yet.")); });
  }

  function addCameras(svg, st) {
    var rot = (M.plan_rotation || 0) * Math.PI / 180, ns = "http://www.w3.org/2000/svg";
    Object.keys(M.panos || {}).forEach(function (pid) {
      var p = M.panos[pid], r = byId[pid];
      if (!r || r.storey !== st.name) return;
      var x = p.pos[0] * Math.cos(rot) - p.pos[1] * Math.sin(rot), y = p.pos[0] * Math.sin(rot) + p.pos[1] * Math.cos(rot);
      var g = document.createElementNS(ns, "rect");
      g.setAttribute("x", x - 0.2); g.setAttribute("y", -y - 0.2); g.setAttribute("width", 0.4); g.setAttribute("height", 0.4);
      g.setAttribute("class", "cam"); g.dataset.pano = pid;
      var t = document.createElementNS(ns, "title"); t.textContent = "360 panorama: " + r.name; g.appendChild(t);
      svg.appendChild(g);
    });
  }

  function selectItem(id) {
    var it = byId[id]; if (!it) return;
    cur.sel = id;
    var svg = $("#plan svg");
    if (svg) {
      svg.querySelectorAll(".on,.unit-on").forEach(function (n) { n.classList.remove("on", "unit-on"); });
      var n = svg.querySelector('[data-room="' + CSS.escape(id) + '"],[data-unit="' + CSS.escape(id) + '"]');
      if (n) n.classList.add("on");
      if (it.unit) { var u = svg.querySelector('[data-unit="' + CSS.escape(it.unit) + '"]'); if (u) u.classList.add("unit-on"); }
    }
    document.querySelectorAll(".cell").forEach(function (c) { c.setAttribute("aria-pressed", c.dataset.unit === id || c.dataset.unit === it.unit); });
    showDetail(it);
  }

  function hideDetail() { $("#detail").hidden = true; }

  function showDetail(it) {
    var isUnit = !!it.ifc && !("unit" in it);
    $("#d-kind").textContent = isUnit ? "Residence" : (it.unit ? "Room in " + byId[it.unit].name : "Common area");
    $("#d-name").textContent = it.name;
    var dl = $("#d-facts"); dl.innerHTML = "";
    var add = function (k, v) { if (v == null || v === "") return; dl.appendChild(el("dt", null, k)); dl.appendChild(el("dd", null, v)); };
    add("Level", title(it.storey));
    add("Area", m2(it.area));
    add("Area from", it.area_source);
    if (!isUnit) add("Named from", it.named_by || "Not named in the model");
    if (isUnit) {
      var rooms = M.rooms.filter(function (r) { return r.unit === it.id; });
      add("Areas inside", rooms.length ? rooms.length + " (tap one on the plan)" : "");
    }
    var act = $("#d-actions"); act.innerHTML = "";
    var panoIds = Object.keys(M.panos || {}).filter(function (p) { return p === it.id || (isUnit && byId[p] && byId[p].unit === it.id); });
    panoIds.forEach(function (p) {
      var b = el("button", "btn", "360 view" + (panoIds.length > 1 ? ": " + byId[p].name : "")); b.type = "button";
      b.addEventListener("click", function () { openPano(p, true); }); act.appendChild(b);
    });
    if (!panoIds.length) { var n = el("span", "btn off", "No 360 view yet"); act.appendChild(n); }
    var a = el("a", "btn", "Open in 3D"); a.href = exploreHref(it); a.target = "_blank"; a.rel = "noopener"; act.appendChild(a);
    (M.hero || []).filter(function (h) { return h.room === it.id || (isUnit && byId[h.room] && byId[h.room].unit === it.id); }).forEach(function (h) {
      var r = el("a", "btn", "Render: " + (h.label || "still")); r.href = h.src; r.target = "_blank"; act.appendChild(r);
    });
    var fb = $("#d-finishes"); fb.innerHTML = "";
    var fins = it.finishes || [];
    if (!isUnit && it.unit && !fins.length) fins = byId[it.unit].finishes || [];
    fb.appendChild(el("p", "eyebrow", "Finishes from the spec library"));
    if (!M.speclib) fb.appendChild(el("p", "muted small", "No spec library linked to this project."));
    else if (!fins.length) fb.appendChild(el("p", "muted small", "Nothing in the schedule names this area. Placeholder: finishes to be confirmed."));
    else {
      if (!it.finishes || !it.finishes.length) fb.appendChild(el("p", "muted small", "General finishes for the residence (the schedule names nothing for this room on its own)."));
      var groups = {};
      fins.forEach(function (f) { (groups[f.category || "Other"] = groups[f.category || "Other"] || []).push(f); });
      Object.keys(groups).sort().forEach(function (g) {
        var gb = el("div", "fin-group"); gb.appendChild(el("h4", null, g));
        groups[g].forEach(function (f) {
          var row = el("div", "fin");
          if (f.thumb) { var im = el("img"); im.src = f.thumb; im.alt = ""; im.loading = "lazy"; row.appendChild(im); } else row.appendChild(el("span", "sw"));
          var t = el("div"); t.appendChild(el("b", null, [f.code, f.item].filter(Boolean).join(" · ")));
          t.appendChild(el("span", null, " " + [f.maker, f.range, f.model, f.finish].filter(Boolean).join(", ")));
          t.appendChild(el("small", null, "Scheduled for: " + (f.location || "") + (f.source ? " · " + f.source : "")));
          row.appendChild(t); gb.appendChild(row);
        });
        fb.appendChild(gb);
      });
    }
    $("#detail").hidden = false;
  }

  // ------------------------------------------------------------ panoramas
  function buildPanos() {
    var ids = Object.keys(M.panos || {});
    var tabs = $("#pano-tabs");
    if (!ids.length) {
      $("#pano").innerHTML = ""; var ph = el("div", "placeholder"); ph.appendChild(el("strong", null, "360 views coming"));
      ph.appendChild(el("span", null, "Panoramas haven't been rendered for this project yet.")); $("#pano").appendChild(ph);
      return;
    }
    ids.forEach(function (id) {
      var b = el("button", null, byId[id] ? byId[id].name + " · " + title(byId[id].storey) : id); b.type = "button"; b.setAttribute("role", "tab"); b.dataset.pano = id;
      b.addEventListener("click", function () { openPano(id); }); tabs.appendChild(b);
    });
    pano = new window.Pano($("#pano"), function (to) { openPano(to); });
    openPano(ids[0]);
  }

  function openPano(id, scroll) {
    var p = M.panos[id]; if (!p || !pano) return;
    panoCur = id;
    document.querySelectorAll("#pano-tabs button").forEach(function (b) { b.setAttribute("aria-selected", b.dataset.pano === id); });
    pano.show(p);
    var r = byId[id];
    $("#pano-stamp").textContent = (r ? r.name + ", " + title(r.storey) + ". " : "") + (p.quality || "Preview render") + ". " + (p.finishes_note || "");
    $("#pano-note").textContent = p.note || "";
    if (scroll) $("#panoramas").scrollIntoView();
  }

  // ------------------------------------------------------------ explore + stills
  function buildExplore() {
    var box = $("#explore-box");
    if (!X) {
      var ph = el("div", "placeholder"); ph.appendChild(el("strong", null, "3D view coming"));
      ph.appendChild(el("span", null, "The real-time model of this building is still being built. Plans and panoramas above are ready."));
      box.appendChild(ph); return;
    }
    var f = el("iframe"); f.title = "3D model of " + M.name; f.loading = "lazy"; f.src = "explore/index.html?view=exterior";
    f.setAttribute("allowfullscreen", ""); box.appendChild(f);
    var links = el("div", "explore-links");
    (X.views || []).forEach(function (v) {
      var a = el("a", "btn", v.indexOf("room:") === 0 ? ((X.rooms || []).find(function (r) { return "room:" + r.id === v; }) || { name: v }).name : title(v));
      a.href = "explore/index.html?view=" + encodeURIComponent(v); a.target = "_blank"; a.rel = "noopener"; links.appendChild(a);
    });
    box.after(links);
  }

  function buildStills() {
    if (!M.hero || !M.hero.length) return;
    $("#stills").hidden = false;
    M.hero.forEach(function (h) {
      var fig = el("figure"), im = el("img"); im.src = h.src; im.alt = h.label || ""; im.loading = "lazy";
      fig.appendChild(im); fig.appendChild(el("figcaption", null, [h.label, h.note].filter(Boolean).join(". "))); $("#stills-list").appendChild(fig);
    });
  }

  // ------------------------------------------------------------ boot
  fetch("manifest.json").then(function (r) { return r.json(); }).then(function (m) {
    M = m;
    m.units.forEach(function (u) { byId[u.id] = u; });
    m.rooms.forEach(function (r) { byId[r.id] = r; });
    document.title = m.name + " · Showcase";
    document.querySelectorAll("[data-bind]").forEach(function (n) { n.textContent = m[n.dataset.bind] || ""; });
    $("#source-line").textContent = "Drawn from " + m.source + " · built " + m.built.replace("T", " ") + (m.speclib ? " · finishes from the spec library, job " + m.speclib.job : "");
    $("#cut").textContent = m.cut_height;
    $("#disclaimer").textContent = m.disclaimer || "";
    $("#detail .close").addEventListener("click", hideDetail);
    return fetch(m.explore.replace("index.html", "explore.json")).then(function (r) { return r.ok ? r.json() : null; }).catch(function () { return null; });
  }).then(function (x) {
    X = x;
    buildStack();
    // deep links: #room=<id>, #unit=<id>, #level=<id>, #pano=<id>
    var h = {}; location.hash.slice(1).split("&").forEach(function (kv) { var p = kv.split("="); if (p[1]) h[p[0]] = decodeURIComponent(p[1]); });
    var pick = byId[h.room || h.unit], first = M.storeys.find(function (s) { return s.units.length; }) || M.storeys[0];
    if (h.focus) {  // &focus=1: show only the linked section (a shareable single view; also used for screenshots)
      var sec = h.pano ? "#panoramas" : h.explore ? "#explore" : "#plans";
      document.body.dataset.focus = "1"; $(sec).classList.add("focus");
    }
    if (pick) { selectStorey(pick.storey, pick.id); if (!h.focus) setTimeout(function () { $("#plans").scrollIntoView(); }, 50); }
    else if (h.level && storeyOf(h.level)) selectStorey(h.level);
    else if (first) selectStorey(first.id);
    buildPanos(); buildExplore(); buildStills();
    if (h.pano && M.panos[h.pano]) openPano(h.pano, !h.focus);
  }).catch(function (e) {
    document.querySelector("main").appendChild(el("p", "band", "Couldn't load manifest.json. Serve this folder with a static server (e.g. npx http-server)."));
    console.error(e);
  });
})();
